// ============================================================================
//                    C++ STANDARD HEADER FILES
// ============================================================================
//
// Header file = aisi file/library interface jisme classes, functions,
//               objects, templates, etc. ki declarations available hoti hain.
//
// Hum header ko #include karke use karte hain:
//
//     #include <header_name>
//
// Example:
//
//     #include <iostream>
//
// ============================================================================


// ============================================================================
// 1. <iostream>
// ============================================================================
//
// Input aur Output ke liye.
//
// Important things:
//
//     cin   -> input lene ke liye
//     cout  -> output print karne ke liye
//     cerr  -> error message ke liye
//     clog  -> logging message ke liye
//
// Example:
//
//     #include <iostream>
//
//     int age;
//     std::cin >> age;
//     std::cout << age;
//
// ============================================================================


// ============================================================================
// 2. <string>
// ============================================================================
//
// std::string ko use karne ke liye.
//
// Example:
//
//     #include <string>
//
//     std::string name = "Vikas";
//
// ============================================================================


// ============================================================================
// 3. <vector>
// ============================================================================
//
// std::vector = dynamic array.
//
// Matlab aisa array jiska size runtime par change ho sakta hai.
//
// Example:
//
//     #include <vector>
//
//     std::vector<int> numbers = {10, 20, 30};
//
// ============================================================================


// ============================================================================
// 4. <array>
// ============================================================================
//
// Fixed-size std::array ke liye.
//
// Example:
//
//     #include <array>
//
//     std::array<int, 5> numbers;
//
// ============================================================================


// ============================================================================
// 5. <list>
// ============================================================================
//
// std::list container ke liye.
//
// Example:
//
//     #include <list>
//
//     std::list<int> numbers;
//
// ============================================================================


// ============================================================================
// 6. <deque>
// ============================================================================
//
// std::deque (Double Ended Queue) ke liye.
//
// Front aur back dono sides se efficiently elements add/remove
// kar sakte hain.
//
// Example:
//
//     #include <deque>
//
//     std::deque<int> numbers;
//
// ============================================================================


// ============================================================================
// 7. <stack>
// ============================================================================
//
// std::stack ke liye.
//
// Stack follows:
//
//     LIFO = Last In, First Out
//
// Example:
//
//     #include <stack>
//
//     std::stack<int> s;
//
// ============================================================================


// ============================================================================
// 8. <queue>
// ============================================================================
//
// std::queue ke liye.
//
// Queue follows:
//
//     FIFO = First In, First Out
//
// Example:
//
//     #include <queue>
//
//     std::queue<int> q;
//
// ============================================================================


// ============================================================================
// 9. <map>
// ============================================================================
//
// std::map ke liye.
//
// Data key-value pairs mein store hota hai.
//
// Example:
//
//     #include <map>
//
//     std::map<std::string, int> marks;
//
// ============================================================================


// ============================================================================
// 10. <unordered_map>
// ============================================================================
//
// std::unordered_map ke liye.
//
// Key-value pairs store karta hai, lekin elements generally
// hash table based organization mein hote hain.
//
// Example:
//
//     #include <unordered_map>
//
//     std::unordered_map<std::string, int> marks;
//
// ============================================================================


// ============================================================================
// 11. <set>
// ============================================================================
//
// std::set ke liye.
//
// Generally unique elements store karta hai.
//
// Example:
//
//     #include <set>
//
//     std::set<int> numbers;
//
// ============================================================================


// ============================================================================
// 12. <unordered_set>
// ============================================================================
//
// std::unordered_set ke liye.
//
// Unique elements ko hash table based organization mein store karta hai.
//
// Example:
//
//     #include <unordered_set>
//
//     std::unordered_set<int> numbers;
//
// ============================================================================


// ============================================================================
// 13. <utility>
// ============================================================================
//
// std::pair, std::move, std::swap etc. ke liye.
//
// Example:
//
//     #include <utility>
//
//     std::pair<int, std::string> student;
//
// ============================================================================


// ============================================================================
// 14. <algorithm>
// ============================================================================
//
// Bahut saare common algorithms ke liye.
//
// Examples:
//
//     sort()
//     reverse()
//     find()
//     max()
//     min()
//     count()
//
// Example:
//
//     #include <algorithm>
//
//     sort(arr.begin(), arr.end());
//
// ============================================================================


// ============================================================================
// 15. <cmath>
// ============================================================================
//
// Mathematical functions ke liye.
//
// Examples:
//
//     sqrt()
//     pow()
//     sin()
//     cos()
//     ceil()
//     floor()
//
// Example:
//
//     #include <cmath>
//
//     double result = std::sqrt(25);
//
// ============================================================================


// ============================================================================
// 16. <cstdlib>
// ============================================================================
//
// General-purpose functions.
//
// Examples:
//
//     abs()
//     rand()
//     srand()
//     exit()
//
// ============================================================================


// ============================================================================
// 17. <ctime>
// ============================================================================
//
// Date/time related C-style functionality.
//
// Example:
//
//     #include <ctime>
//
// ============================================================================


// ============================================================================
// 18. <chrono>
// ============================================================================
//
// Modern C++ mein time duration, clocks aur time measurement ke liye.
//
// Example:
//
//     #include <chrono>
//
// ============================================================================


// ============================================================================
// 19. <iomanip>
// ============================================================================
//
// Output formatting ke liye.
//
// Examples:
//
//     setw()
//     setprecision()
//     fixed()
//     setfill()
//
// Example:
//
//     #include <iomanip>
//
//     std::cout << std::fixed << std::setprecision(2) << 12.3456;
//
// ============================================================================


// ============================================================================
// 20. <fstream>
// ============================================================================
//
// Files ke saath read/write karne ke liye.
//
// Examples:
//
//     std::ifstream -> file se read
//     std::ofstream -> file mein write
//     std::fstream  -> read + write
//
// Example:
//
//     #include <fstream>
//
// ============================================================================


// ============================================================================
// 21. <sstream>
// ============================================================================
//
// String ko stream ki tarah use karne ke liye.
//
// Examples:
//
//     std::stringstream
//     std::istringstream
//     std::ostringstream
//
// ============================================================================


// ============================================================================
// 22. <cctype>
// ============================================================================
//
// Characters ko check/modify karne ke liye.
//
// Examples:
//
//     isalpha()
//     isdigit()
//     isupper()
//     islower()
//     toupper()
//     tolower()
//
// ============================================================================


// ============================================================================
// 23. <cstring>
// ============================================================================
//
// C-style strings ke operations ke liye.
//
// Examples:
//
//     strlen()
//     strcpy()
//     strcmp()
//     strcat()
//
// IMPORTANT:
// Modern C++ mein normal text ke liye std::string generally
// prefer kiya jata hai.
//
// ============================================================================


// ============================================================================
// 24. <memory>
// ============================================================================
//
// Smart pointers aur memory-related utilities.
//
// Examples:
//
//     std::unique_ptr
//     std::shared_ptr
//     std::weak_ptr
//     std::make_unique()
//     std::make_shared()
//
// ============================================================================


// ============================================================================
// 25. <functional>
// ============================================================================
//
// Function objects, std::function, bind, etc. ke liye.
//
// Example:
//
//     std::function<int(int, int)> add;
//
// ============================================================================


// ============================================================================
// 26. <optional>
// ============================================================================
//
// C++17 se available.
//
// Aisa object jo value contain kar sakta hai ya value nahi bhi.
//
// Example:
//
//     std::optional<int> age;
//
// ============================================================================


// ============================================================================
// 27. <variant>
// ============================================================================
//
// C++17 se available.
//
// Ek variable mein different possible types mein se ek value
// store karne ke liye.
//
// Example:
//
//     std::variant<int, double, std::string> value;
//
// ============================================================================


// ============================================================================
// 28. <tuple>
// ============================================================================
//
// Multiple different types ki values ko ek object mein store karne ke liye.
//
// Example:
//
//     std::tuple<int, std::string, double> student;
//
// ============================================================================


// ============================================================================
// 29. <random>
// ============================================================================
//
// Modern random number generation ke liye.
//
// Example:
//
//     std::random_device
//     std::mt19937
//     std::uniform_int_distribution
//
// ============================================================================


// ============================================================================
// 30. <regex>
// ============================================================================
//
// Regular expressions ke liye.
//
// Example:
//
//     std::regex
//
// ============================================================================


// ============================================================================
// 31. <thread>
// ============================================================================
//
// Multithreading ke liye.
//
// Example:
//
//     std::thread
//
// ============================================================================


// ============================================================================
// 32. <mutex>
// ============================================================================
//
// Threads ke beech shared data ko safely access karne ke liye
// synchronization tools.
//
// Examples:
//
//     std::mutex
//     std::lock_guard
//     std::unique_lock
//
// ============================================================================


// ============================================================================
// 33. <exception>
// ============================================================================
//
// Exception-related functionality.
//
// Example:
//
//     std::exception
//
// ============================================================================


// ============================================================================
// 34. <stdexcept>
// ============================================================================
//
// Standard exception classes.
//
// Examples:
//
//     std::runtime_error
//     std::logic_error
//     std::out_of_range
//
// ============================================================================


// ============================================================================
// 35. <cassert>
// ============================================================================
//
// assert() ke liye.
//
// assert() ka use program mein assumptions/conditions ko check
// karne ke liye kiya jata hai.
//
// Example:
//
//     #include <cassert>
//
//     assert(age >= 0);
//
// ============================================================================


